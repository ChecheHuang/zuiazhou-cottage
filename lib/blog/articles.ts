export const getArticle = (slug: string) => ARTICLES.find((a) => a.slug === slug);

/** 約略閱讀時間：中文每分鐘約 400 字，至少 1 分鐘 */
export const readMinutes = (article: Article) => {
  const chars = article.sections.reduce((n, s) => {
    if (s.kind === "link") return n;
    if ("text" in s) return n + s.text.length;
    if ("items" in s) return n + s.items.join("").length;
    if (s.kind === "table") return n + s.rows.flat().join("").length;
    return n + 200; // 引用網站資料的區塊大概估一下
  }, article.title.length);
  return Math.max(1, Math.round(chars / 400));
};
